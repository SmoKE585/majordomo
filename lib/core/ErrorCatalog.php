    /**
     * Описание кода ошибки для группы в журнале.
     *
     * @return array{TITLE:string,DETAILS:string}
     */
    public static function get(string $code): array
    {
        $code = trim($code);
        return self::ENTRIES[$code] ?? array('TITLE' => '', 'DETAILS' => '');
    }

    public static function title(string $code): string
    {
        return self::get($code)['TITLE'];
    }

    public static function details(string $code): string
    {
        return self::get($code)['DETAILS'];
    }

    /**
     * Заполняет пустые TITLE/DETAILS сохранённой группы, не трогая текст,
     * который администратор мог отредактировать вручную.
     *
     * @param array<string,mixed> $record
     * @return array<string,mixed>
     */
    public static function fill(array $record, string $code): array
    {
        $entry = self::get($code);
        if ($entry['TITLE'] !== '' && trim((string)($record['TITLE'] ?? '')) === '') {
            $record['TITLE'] = $entry['TITLE'];
        }
        if ($entry['DETAILS'] !== '' && trim((string)($record['DETAILS'] ?? '')) === '') {
            $record['DETAILS'] = $entry['DETAILS'];
        }
        return $record;
    }

    /** @return string[] */
    public static function codes(): array
    {
        return array_keys(self::ENTRIES);
    }
}
