<?php

namespace MajorDoMo\Core;

/**
 * Compiled configuration cache.
 *
 * The cache contains the parsed `.env` values (including secrets), so it lives
 * below `cms/cached/`, which is outside the document root and denied by nginx.
 * The file is a plain PHP array, which keeps it compatible with OPcache.
 *
 * A stale or unreadable cache never stops the application: Config falls back to
 * parsing `.env` again and rewrites the file on the next boot.
 */
final class ConfigCache
{
    private const RELATIVE_PATH = 'cms/cached/config.php';

    public static function path(string $root): string
    {
        return rtrim($root, '/\\') . DIRECTORY_SEPARATOR . str_replace('/', DIRECTORY_SEPARATOR, self::RELATIVE_PATH);
    }

    /**
     * @return array{raw: array<string, string>}|null
     */
    public static function read(string $root, string $fingerprint): ?array
    {
        $path = self::path($root);
        if (!is_file($path) || !is_readable($path)) {
            return null;
        }
        try {
            $data = @include $path;
        } catch (\Throwable $e) {
            // A truncated/corrupted cache must fall back to parsing .env.
            return null;
        }
        if (!is_array($data) || ($data['fingerprint'] ?? null) !== $fingerprint || !isset($data['raw']) || !is_array($data['raw'])) {
            return null;
        }
        return array('raw' => $data['raw']);
    }

    /**
     * @param array<string, string> $raw
     */
    public static function write(string $root, array $raw, string $fingerprint): void
    {
        $path = self::path($root);
        $directory = dirname($path);
        if (!is_dir($directory) && !@mkdir($directory, 0775, true) && !is_dir($directory)) {
            return;
        }
        if (!is_writable($directory) && !is_writable($path)) {
            return;
        }

        $payload = array('fingerprint' => $fingerprint, 'raw' => $raw);
        $code = "<?php\n"
            . "// Generated by MajorDoMo ConfigCache. Do not edit; change .env and run `php tools/config.php cache`.\n"
            . 'return ' . var_export($payload, true) . ";\n";

        $temporary = $path . '.' . bin2hex(random_bytes(6)) . '.tmp';
        if (@file_put_contents($temporary, $code, LOCK_EX) === false) {
            return;
        }
        @chmod($temporary, 0640);

        if (!@rename($temporary, $path)) {
            // Windows does not always replace an existing target atomically.
            @unlink($path);
            if (!@rename($temporary, $path)) {
                @unlink($temporary);
                return;
            }
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
    }

    public static function clear(string $root): bool
    {
        $path = self::path($root);
        if (!is_file($path)) {
            return true;
        }
        $removed = @unlink($path);
        if ($removed && function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true);
        }
        return $removed;
    }

    /**
     * Cheap fingerprint: schema changes and both env files participate.
     *
     * @param array<string, mixed> $schema
     */
    public static function fingerprint(string $root, array $schema): string
    {
        $parts = array(self::schemaHash($schema));
        foreach (array('.env', '.env.local') as $file) {
            $path = rtrim($root, '/\\') . DIRECTORY_SEPARATOR . $file;
            // Hash the contents, not only mtime: editors can rewrite a value
            // within the same second and keep the same size.
            $parts[] = $file . ':' . (is_file($path) ? (string)@sha1_file($path) : 'missing');
        }
        return sha1(implode('|', $parts));
    }

    /**
     * @param array<string, mixed> $schema
     */
    private static function schemaHash(array $schema): string
    {
        $description = array();
        foreach ($schema as $key => $definition) {
            $description[$key] = array(
                $definition['type'] ?? 'string',
                $definition['optional'] ?? false,
                $definition['computed'] ?? false,
                $definition['env'] ?? true,
                $definition['constant'] ?? true,
            );
        }
        return sha1(json_encode($description));
    }
}
